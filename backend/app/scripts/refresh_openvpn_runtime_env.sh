#!/bin/bash
# Build the minimal environment consumed by OpenVPN's unprivileged hooks.
# The full panel.env contains deployment data and must not be exposed to the
# nobody user. This helper runs as root and publishes only the local API port
# and internal token with ownership matching OpenVPN's configured drop group.
set -Eeuo pipefail

[ "$(id -u)" -eq 0 ] || { echo "refresh_openvpn_runtime_env.sh must run as root" >&2; exit 1; }

INSTALL_DIR="${VPN_PANEL_INSTALL_DIR:-/opt/vpn-panel}"
TARGET_DIR="${VPN_PANEL_OPENVPN_RUNTIME_DIR:-/etc/vpn-panel}"
TARGET_FILE="${TARGET_DIR}/openvpn-hook.env"
PANEL_ENV="${INSTALL_DIR}/panel.env"
BACKEND_ENV="${INSTALL_DIR}/backend/.env"

# Prefer the group declared by live OpenVPN configs. Fall back to the primary
# group of the drop user and finally numeric 65534. Numeric ownership avoids
# distro differences such as nogroup vs nobody.
DROP_USER=""
DROP_GROUP=""
for conf in /etc/openvpn/server/*.conf /etc/openvpn/*.conf; do
  [ -f "$conf" ] || continue
  [ -n "$DROP_USER" ] || DROP_USER="$(awk '$1=="user" && $2!="" {print $2; exit}' "$conf" 2>/dev/null || true)"
  [ -n "$DROP_GROUP" ] || DROP_GROUP="$(awk '$1=="group" && $2!="" {print $2; exit}' "$conf" 2>/dev/null || true)"
  [ -n "$DROP_USER" ] && [ -n "$DROP_GROUP" ] && break
done
DROP_USER="${DROP_USER:-nobody}"

OPENVPN_GID=""
if [ -n "$DROP_GROUP" ]; then
  OPENVPN_GID="$(getent group "$DROP_GROUP" 2>/dev/null | awk -F: '{print $3; exit}' || true)"
fi
if ! [[ "$OPENVPN_GID" =~ ^[0-9]+$ ]]; then
  OPENVPN_GID="$(id -g "$DROP_USER" 2>/dev/null || true)"
fi
if ! [[ "$OPENVPN_GID" =~ ^[0-9]+$ ]]; then
  OPENVPN_GID=65534
fi

# This directory is shared with /etc/vpn-panel/xray.  It must not be tied to
# only one service group.  Execute-only access lets unprivileged services
# traverse to their known file while child permissions remain authoritative.
install -d -o root -g root -m 0711 "$TARGET_DIR"

# Exact-credential success cache used only when the local API is temporarily
# unavailable.  Files contain an HMAC and timestamp, never a plaintext password.
AUTH_CACHE_PARENT="/run/vpn-panel"
AUTH_CACHE_DIR="$AUTH_CACHE_PARENT/openvpn-auth-cache"
install -d -o root -g root -m 0711 "$AUTH_CACHE_PARENT"
install -d -o root -g "$OPENVPN_GID" -m 0770 "$AUTH_CACHE_DIR"
find "$AUTH_CACHE_DIR" -maxdepth 1 -type f -mmin +15 -delete 2>/dev/null || true

/usr/bin/python3 - "$PANEL_ENV" "$BACKEND_ENV" "$TARGET_FILE" "$OPENVPN_GID" <<'PY'
from __future__ import annotations

import os
import shlex
import sys
import tempfile
from pathlib import Path

panel_path = Path(sys.argv[1])
backend_path = Path(sys.argv[2])
target = Path(sys.argv[3])
gid = int(sys.argv[4])


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    text = path.read_text(encoding="utf-8", errors="replace")
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if not key:
            continue
        value = value.strip()
        try:
            parsed = shlex.split(value, posix=True)
            value = parsed[0] if len(parsed) == 1 else value
        except ValueError:
            value = value.strip("'\"")
        values[key] = value
    return values

panel = read_env(panel_path)
backend = read_env(backend_path)
port = (panel.get("BACKEND_PORT") or backend.get("BACKEND_PORT") or "").strip()
token = (backend.get("INTERNAL_API_TOKEN") or panel.get("INTERNAL_API_TOKEN") or "").strip()

if not port.isdigit() or not (1 <= int(port) <= 65535):
    raise SystemExit("BACKEND_PORT is missing or invalid; OpenVPN hook environment was not changed")
if len(token) < 16 or "\n" in token or "\r" in token:
    raise SystemExit("INTERNAL_API_TOKEN is missing or invalid; OpenVPN hook environment was not changed")

payload = (
    "# Generated by VPN Panel. Contains only values required by OpenVPN hooks.\n"
    f"BACKEND_PORT={shlex.quote(port)}\n"
    f"INTERNAL_API_TOKEN={shlex.quote(token)}\n"
)

target.parent.mkdir(parents=True, exist_ok=True)
fd, tmp_name = tempfile.mkstemp(prefix=".openvpn-hook.env.", dir=str(target.parent))
try:
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())
    os.chown(tmp_name, 0, gid)
    os.chmod(tmp_name, 0o640)
    os.replace(tmp_name, target)
    dir_fd = os.open(target.parent, os.O_DIRECTORY)
    try:
        os.fsync(dir_fd)
    finally:
        os.close(dir_fd)
finally:
    try:
        os.unlink(tmp_name)
    except FileNotFoundError:
        pass
PY

# Verify using the exact uid/gid that OpenVPN uses after dropping privileges.
# setpriv can reproduce a configured group even when its name differs from the
# drop user's primary group (for example nobody vs nogroup).
DROP_UID="$(id -u "$DROP_USER" 2>/dev/null || true)"
if command -v setpriv >/dev/null 2>&1 && [[ "$DROP_UID" =~ ^[0-9]+$ ]]; then
  setpriv --reuid "$DROP_UID" --regid "$OPENVPN_GID" --clear-groups test -r "$TARGET_FILE" || {
    echo "OpenVPN uid=$DROP_UID gid=$OPENVPN_GID cannot read $TARGET_FILE" >&2
    exit 1
  }
elif command -v runuser >/dev/null 2>&1 && id "$DROP_USER" >/dev/null 2>&1      && [ "$(id -g "$DROP_USER")" = "$OPENVPN_GID" ]; then
  runuser -u "$DROP_USER" -- test -r "$TARGET_FILE" || {
    echo "OpenVPN drop user $DROP_USER cannot read $TARGET_FILE" >&2
    exit 1
  }
else
  /usr/bin/python3 - "$TARGET_FILE" "$OPENVPN_GID" <<'PYVERIFY'
import os, stat, sys
path = sys.argv[1]
gid = int(sys.argv[2])
st = os.stat(path)
if st.st_uid != 0 or st.st_gid != gid or stat.S_IMODE(st.st_mode) != 0o640:
    raise SystemExit("OpenVPN hook environment permissions are invalid")
PYVERIFY
fi

logger -t vpn-panel-openvpn-auth "runtime env ready path=${TARGET_FILE} drop_user=${DROP_USER} gid=${OPENVPN_GID}"
printf '[✓] OpenVPN hook environment refreshed: %s (user=%s gid=%s)\n' "$TARGET_FILE" "$DROP_USER" "$OPENVPN_GID"
