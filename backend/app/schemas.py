    sniffing_route_only: bool = True
    accept_proxy_protocol: bool = False
    tcp_fast_open: bool = False
    external_proxy_enabled: bool = False
    external_proxy_address: str = Field("127.0.0.1", max_length=253)
    external_proxy_port: int = Field(1080, ge=1, le=65535)

    @field_validator("bind_address")
    @classmethod
    def validate_bind_address(cls, value: str) -> str:
        value = (value or "").strip()
        if value in {"0.0.0.0", "::", "127.0.0.1", "::1"}:
            return value
        if not DNS_ADDR_RE.match(value):
            raise ValueError("آدرس Bind باید یک IPv4/IPv6 معتبر باشد")
        return value

    @field_validator("ws_path")
    @classmethod
    def validate_ws_path(cls, value: str) -> str:
        value = (value or "").strip()
        if not value.startswith("/") or " " in value or "?" in value or "#" in value:
            raise ValueError("مسیر WebSocket باید با / شروع شود و فاصله، ? یا # نداشته باشد")
        return value

    @field_validator("tls_domain")
    @classmethod
    def validate_tls_domain(cls, value: Optional[str]) -> Optional[str]:
        value = (value or "").strip().lower()
        if not value:
            return None
        if not re.match(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$", value):
            raise ValueError("دامنه TLS معتبر نیست")
        return value

    @model_validator(mode="after")
    def validate_combinations(self):
        if self.tls_enabled and not self.tls_domain:
            raise ValueError("برای TLS باید دامنه وارد شود")
        if self.protocol == "vmess" and self.flow:
            raise ValueError("Flow فقط برای VLESS قابل استفاده است")
        if self.flow and not (self.protocol == "vless" and self.transport == "tcp" and self.tls_enabled):
            raise ValueError("xtls-rprx-vision فقط برای VLESS روی TCP همراه TLS قابل استفاده است")
        return self


