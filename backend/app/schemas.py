# یوزرنیم فقط انگلیسی: حروف/عدد انگلیسی، خط تیره، زیرخط و نقطه (هم برای
# ادمین‌ها و هم برای کاربران VPN استفاده می‌شود).
USERNAME_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
# پسورد فقط انگلیسی: حروف بزرگ/کوچک انگلیسی، عدد و علائم رایج روی کیبورد
# انگلیسی؛ هیچ حرف فارسی/غیرانگلیسی یا فاصله مجاز نیست. حروف بزرگ و کوچک هم
# در این regex و هم در مقایسه‌ی نهایی (chap-secrets / هش پسورد) متفاوت
# در نظر گرفته می‌شوند.
PASSWORD_RE = re.compile(r"^[A-Za-z0-9!@#$%^&*()_+\-=\[\]{}:;,.<>?/~`|]+$")
# آدرس DNS که ocserv برای کلاینت‌های OpenConnect می‌فرستد - IPv4 یا IPv6 ساده
# (بدون رزولوشن دامنه، دقیقاً همان چیزی که ocserv.conf انتظار دارد).
DNS_ADDR_RE = re.compile(r"^([0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}|[0-9a-fA-F:]+)$")

# Internal sub-admin license format. New keys have four groups of five
# uppercase letters/digits. Legacy ADM-prefixed keys remain accepted so an
# update never invalidates licenses generated by older panel versions.
INTERNAL_LICENSE_RE = re.compile(r"^[A-Z0-9]{5}(?:-[A-Z0-9]{5}){3}$")
LEGACY_INTERNAL_LICENSE_RE = re.compile(r"^ADM-[A-Z0-9]{5}(?:-[A-Z0-9]{5}){3}$")


def _validate_internal_license_code(value: str) -> str:
    if value != value.strip() or value != value.upper():
        raise ValueError("کد لایسنس باید دقیقاً با حروف بزرگ وارد شود")
    if not (INTERNAL_LICENSE_RE.fullmatch(value) or LEGACY_INTERNAL_LICENSE_RE.fullmatch(value)):
        raise ValueError("ساختار کد لایسنس معتبر نیست؛ نمونه: XQ5NU-2QKH7-87CAS-AH74S")
    return value


def _validate_english_username(v: str, label: str = "یوزرنیم") -> str:
    if not USERNAME_RE.match(v):
        raise ValueError(f"{label} فقط می‌تواند شامل حروف/عدد انگلیسی، خط تیره (-)، زیرخط (_) و نقطه (.) باشد")
    return v


def _validate_english_password(v: str, label: str = "پسورد") -> str:
    if not PASSWORD_RE.match(v):
        raise ValueError(f"{label} فقط می‌تواند شامل حروف انگلیسی، عدد و علائم رایج (بدون فاصله و بدون حروف فارسی) باشد")
    return v


