    minutes_remaining: Optional[int] = None
    expires_at_jalali_display: Optional[str] = None
    created_at_jalali_display: Optional[str] = None
    first_online_jalali_display: Optional[str] = None
    total_days_purchased: Optional[int] = None
    last_checked_at: Optional[str] = None
    message: str
    reserved_count: int = 0
    # مجموع روزهای باقی‌مانده‌ی لایسنس فعلی + همه‌ی لایسنس‌های رزروشده در
    # صف (هرکدام که هنوز شمارش‌شان شروع نشده، با کل مدتشان (duration_days)
    # به این مجموع اضافه می‌شوند) - یعنی «اگر همه‌ی این کدها پشت سر هم
    # مصرف شوند، رویهم چند روز سرویس باقی مانده».
    total_days_remaining_with_queue: Optional[int] = None
    # پیام یک‌باره‌ی «لایسنس قبلی پاک/ریست/منقضی شد و لایسنس رزروشده‌ی بعدی
    # خودکار جایگزین شد» - فقط به سوپرادمین نشان داده می‌شود و بعد از دیدنش
    # با /api/license/switch-notice/ack پاک می‌شود.
    switch_notice: Optional[str] = None
    # نتیجه‌ی کلیک روی دکمه‌ی فعال‌سازی: اگر لایسنس فعلی بیش از یک دقیقه
    # اعتبار داشته باشد، کلید جدید به صف رزرو می‌رود؛ در غیر این صورت همان
    # لحظه فعال می‌شود. فرانت‌اند از این مقدار برای پیام دقیق استفاده می‌کند.
    activation_action: Optional[str] = None  # activated / reserved


