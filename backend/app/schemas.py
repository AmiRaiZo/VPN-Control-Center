class VpnProtocolSettings(BaseModel):
    l2tp_enabled: bool = True
    l2tp_port: int = Field(1701, ge=1, le=65535)
    # MTU/MRU پی‌پی‌پی روی تونل L2TP. پیش‌فرض هر دو 1400 (کمتر از 1500
    # استاندارد، به‌خاطر سربار L2TP/IPsec روی هر پکت) تا پکت‌های بزرگ TCP
    # (مثلاً هنگام آپلود) به‌جای گم‌شدن در فرگمنتیشن/PMTU black hole، از همان
    # ابتدا با اندازه‌ی درست فرستاده شوند. بازه‌ی مجاز محافظه‌کارانه است: خیلی
    # کوچیک (کمتر از 576) فرگمنتیشن بیش از حد ایجاد می‌کند، خیلی بزرگ (بیشتر
    # از 1460) دوباره همان مشکل قبلی (قطع اتصال هنگام آپلود) را برمی‌گرداند.
    l2tp_mtu: int = Field(1400, ge=576, le=1460)
    l2tp_mru: int = Field(1400, ge=576, le=1460)
    l2tp_dns1: str = Field("8.8.8.8", max_length=64)
    l2tp_dns2: str = Field("8.8.4.4", max_length=64)
    l2tp_local_ip: str = Field("10.10.10.1", max_length=64)
    l2tp_ip_range: str = Field("10.10.10.10-10.10.10.250", max_length=128)
    l2tp_client_to_client: bool = False

    pptp_enabled: bool = True
    pptp_dns1: str = Field("8.8.8.8", max_length=64)
    pptp_dns2: str = Field("8.8.4.4", max_length=64)
