class NodeCreate(BaseModel):
    name: str = Field(..., min_length=2, max_length=96)
    api_url: str = Field(..., min_length=8, max_length=512)
    api_token: str = Field(..., min_length=16, max_length=512)
    enabled: bool = True
    verify_tls: bool = True
    weight: int = Field(100, ge=1, le=1000)
    ssh_host: Optional[str] = Field(None, max_length=255)
    ssh_port: int = Field(22, ge=1, le=65535)
    ssh_username: Optional[str] = Field(None, max_length=128)
    ssh_password: Optional[str] = Field(None, max_length=512)
    save_ssh_password: bool = False
    clear_ssh_password: bool = False
    panel_admin_username: Optional[str] = Field(None, max_length=128)
    panel_admin_password: Optional[str] = Field(None, max_length=512)
    save_panel_admin_credentials: bool = False
    remote_admin_enabled: bool = False
    user_assignment_enabled: bool = True
    node_panel_enabled: bool = True
    protocol_domains: dict[str, str] = Field(default_factory=dict)

    @field_validator("protocol_domains")
    @classmethod
    def validate_protocol_domains(cls, value: dict[str, str]) -> dict[str, str]:
        allowed = {"l2tp", "pptp", "openvpn", "openconnect", "sstp", "ikev2", "vmess", "vless"}
        cleaned: dict[str, str] = {}
        for key, domain in (value or {}).items():
            if key not in allowed:
                continue
            domain = str(domain or "").strip().lower().rstrip(".")
            if not domain:
                continue
            if not re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+", domain):
                raise ValueError(f"دامنه پروتکل {key} معتبر نیست")
            cleaned[key] = domain
        return cleaned

    @field_validator("api_url")
    @classmethod
    def validate_api_url(cls, value: str) -> str:
        value = value.strip().rstrip("/")
        if not (value.startswith("https://") or value.startswith("http://")):
            raise ValueError("آدرس API نود باید با http:// یا https:// شروع شود")
        return value


