    tls_domain: Optional[str] = Field(None, max_length=253)
    # flow فقط برای VLESS/TCP/TLS معنی دارد. مقدار خالی یعنی بدون flow.
    flow: Literal["", "xtls-rprx-vision"] = ""
    server_address: Optional[str] = None
    remark: str = Field("", max_length=100)
